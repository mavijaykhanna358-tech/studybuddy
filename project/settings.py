# Stands in for "no database was configured". Django's dummy backend is
# what it uses for an empty DATABASES, and it can never accidentally
# write to SQLite on Render's ephemeral disk, so the deployment fails
# loudly instead of looking healthy and losing every row on the next
# deploy. The system check in project/deployment.py stops each command
# before it runs. A function, because DATABASES is live configuration
# and must not be one shared dict between two settings loads.

def _no_database():

    return {

        'ENGINE': 'django.db.backends.dummy'

    }


if DATABASE_URL:

    # `config()` returns an empty dict when DATABASE_URL is unset and
    # raises UnknownSchemeError when the scheme is unrecognised, so
    # neither a missing nor a malformed value is obvious from the
    # settings alone. Resolve it here instead.

    try:

        DATABASES = {

            'default': dj_database_url.config(
                conn_max_age=600,
                conn_health_checks=True,
                ssl_require=DATABASE_SSL_REQUIRE
            )

        }

    except Exception as error:

        _record(
            'DATABASE_URL',
            'is set but could not be parsed.\n'
            f'  {error}\n'
            f'{DATABASE_URL_HELP}'
        )

        DATABASES = {'default': _no_database()}

    else:

        if not DATABASES['default'].get('ENGINE'):

            _record(
                'DATABASE_URL',
                'is set but produced no database ENGINE, so\n'
                'Django has nothing to connect with.\n'
                f'{DATABASE_URL_HELP}'
            )

            DATABASES = {'default': _no_database()}

elif DATABASE_FALLBACK_ENGINE:

    DATABASES = {

        'default': {

            'ENGINE': DATABASE_FALLBACK_ENGINE,

            'NAME': BASE_DIR / 'db.sqlite3',

        }

    }

else:

    _record(
        'DATABASE_URL',
        'is not set and the SQLite fallback is switched\n'
        'off for production, because Render\'s disk is ephemeral and a\n'
        'SQLite file there would lose every row on the next deploy.\n'
        f'{DATABASE_URL_HELP}\n'
        'For a deliberate SQLite deployment set\n'
        'DATABASE_FALLBACK_ENGINE=django.db.backends.sqlite3'
    )

    DATABASES = {'default': _no_database()}


